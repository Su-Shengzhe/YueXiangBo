#requires -Version 7.0
$ErrorActionPreference='Stop'
$root=Split-Path $PSScriptRoot -Parent
. "$PSScriptRoot/Use-Toolchain.ps1"
$config=Read-LocalConfig "$root/deploy/.env.business"
$directory=Join-Path $root ('.runtime/business/numeric-contract/'+(Get-Date -Format 'yyyyMMdd-HHmmss'))
$null=New-Item -ItemType Directory -Force $directory
$report=@{status='RUNNING';checks=@();sourceFingerprint=(Get-Content "$root/.runtime/backend-build.json" -Raw|ConvertFrom-Json).source.fingerprint}
try {
 $login=Invoke-RestMethod http://127.0.0.1:9090/api/v1/auth/login -Method Post -ContentType application/json -Body (@{username='driver';password=$config.DEMO_DRIVER_PASSWORD}|ConvertTo-Json)
 # Negative order IDs cannot be generated by the application; no money or application is created.
 $cases=@(@{name='fractional-fen-rejected';id=-1;amount=1.5;expected=422},@{name='fractional-id-rejected';id=-1.5;amount=1;expected=422},@{name='integer-request-reaches-order-validation';id=-1;amount=1;expected=404})
 foreach($case in $cases){
  $response=Invoke-WebRequest http://127.0.0.1:9090/api/v1/refund-applications -Method Post -ContentType application/json -Headers @{Authorization='Bearer '+$login.data.accessToken;'Idempotency-Key'=[Guid]::NewGuid().ToString()} -Body (@{reservationId=$case.id;amountFen=$case.amount;reason='numeric contract validation'}|ConvertTo-Json) -SkipHttpErrorCheck
  $report.checks+=@{name=$case.name;expected=$case.expected;actual=$response.StatusCode}
  if($response.StatusCode -ne $case.expected){throw "Numeric contract failed: $($case.name)"}
 }
 $report.status='PASS'
}catch{$report.status='FAIL';$report.error=$_.Exception.Message;throw}
finally{$report|ConvertTo-Json -Depth 5|Set-Content (Join-Path $directory 'results.json');Write-Host "Numeric contract: $($report.status), $directory"}
