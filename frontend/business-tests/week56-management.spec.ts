import { test, expect } from '@playwright/test'

test('register, vehicle, owner publication, property review, window and quoted booking through UI', async ({ page, request }) => {
 const base='http://127.0.0.1:9090/api/v1',suffix=Date.now().toString(36),username='ui_'+suffix,password=crypto.randomUUID()+'Aa9'
 async function api(path:string,token?:string,body?:unknown,method?:string){const r=await request.fetch(base+path,{method:method||(body===undefined?'GET':'POST'),headers:token?{Authorization:'Bearer '+token}:{},data:body});expect(r.ok(),path+': '+await r.text()).toBeTruthy();return (await r.json()).data}
 async function login(name:string,pass:string){await page.getByLabel('账号',{exact:true}).fill(name);await page.getByLabel('密码',{exact:true}).fill(pass);await page.getByRole('button',{name:'登录',exact:true}).click();await expect(page.getByRole('button',{name:'退出登录',exact:true})).toBeVisible()}
 const admin=(await api('/auth/login',undefined,{username:'admin',password:process.env.DEMO_ADMIN_PASSWORD})).accessToken
 const community=await api('/communities',admin,{name:'界面验收_'+suffix,address:'虚拟地址'})
 await page.goto('/')
 await page.getByRole('button',{name:'创建新账号'}).click()
 await page.getByLabel('账号',{exact:true}).fill(username);await page.getByLabel('密码',{exact:true}).fill(password)
 await page.getByRole('button',{name:'注册',exact:true}).click();await expect(page.getByRole('alert')).toContainText('注册成功')
 const newUser=await api('/auth/login',undefined,{username,password})
 await api('/admin/users/'+newUser.user.id+'/roles',admin,{roles:['DRIVER','OWNER']},'PUT')
 await login(username,password)
 await expect(page.getByRole('button',{name:'业主车位管理'})).toBeVisible()
 await page.getByRole('button',{name:'车辆管理',exact:true}).click()
 await page.getByRole('button',{name:'绑定车辆',exact:true}).click()
 await page.getByLabel('车牌号码',{exact:true}).fill('沪A'+Math.floor(Math.random()*90000+10000))
 await page.getByRole('button',{name:'保存',exact:true}).click();await expect(page.locator('.management table tbody tr')).toHaveCount(1)
 await page.getByRole('button',{name:'业主车位管理'}).click()
 await page.getByRole('button',{name:'发布车位',exact:true}).click()
 await page.getByRole('combobox',{name:'所属社区',exact:true}).selectOption(community.id)
 await page.getByLabel('车位编号',{exact:true}).fill('UI-'+suffix)
 await page.getByLabel('位置说明',{exact:true}).fill('地下车库B区')
 await page.getByLabel('证明说明',{exact:true}).fill('界面验收虚拟证明，不对公众展示')
 await page.getByRole('button',{name:'保存',exact:true}).click()
 await expect(page.locator('.management table tbody')).toContainText('草稿')
 await page.getByRole('button',{name:'提交审核',exact:true}).click();await expect(page.locator('.management table tbody')).toContainText('待审核')
 await page.getByRole('button',{name:'退出登录'}).click()
 await login('admin',process.env.DEMO_ADMIN_PASSWORD!)
 await page.getByRole('button',{name:'车位审核',exact:true}).click()
 await page.getByRole('combobox',{name:'审核社区',exact:true}).selectOption(community.id)
 const reviewRow=page.getByRole('row').filter({hasText:'UI-'+suffix})
 await expect(reviewRow).toBeVisible()
 page.once('dialog',dialog=>dialog.accept('界面审核通过'))
 await reviewRow.getByRole('button',{name:'通过',exact:true}).click();await expect(reviewRow).toContainText('审核通过')
 await page.getByRole('button',{name:'退出登录'}).click();await login(username,password)
 await page.getByRole('button',{name:'业主车位管理'}).click();await page.getByRole('button',{name:'共享窗口',exact:true}).click()
 await page.getByLabel('小时价格（分，100分=1元）',{exact:true}).fill('400')
 const start=await page.getByLabel('窗口开始',{exact:true}).inputValue(),end=await page.getByLabel('窗口结束',{exact:true}).inputValue()
 await page.getByRole('button',{name:'保存窗口',exact:true}).click();await expect(page.locator('.window-calendar')).toContainText('¥4.00')
 await page.screenshot({path:process.env.BUSINESS_REPORT_DIR+'/week56-windows.png',fullPage:true})
 await page.getByRole('button',{name:'查询与预约'}).click()
 await page.getByRole('combobox',{name:'社区',exact:true}).selectOption(community.id)
 await page.getByLabel('开始时间',{exact:true}).fill(start);await page.getByLabel('结束时间',{exact:true}).fill(end)
 await page.getByRole('button',{name:'查询车位',exact:true}).click();await expect(page.locator('.space-grid')).toContainText('UI-'+suffix)
 const reserveResponse=page.waitForResponse(r=>r.url().endsWith('/api/v1/reservations')&&r.request().method()==='POST')
 await page.getByRole('button',{name:'预约此车位'}).click()
 const response=await reserveResponse;expect(response.ok()).toBeTruthy();const order=(await response.json()).data
 await expect(page.getByRole('row').filter({hasText:order.reservationId})).toContainText('待付款')
 const token=(await api('/auth/login',undefined,{username,password})).accessToken
 await api('/reservations/'+order.reservationId+'/cancel',token,{})
 await page.getByRole('button',{name:'退出登录'}).click()
})
